import { newSlide, templates } from "./types";
import type { Slide, Template } from "./types";
import { newActivity } from "./activities";

const aliases: Record<string, Template> = {
  intro: "opener", introduction: "opener", objectives: "opener", brief: "opener",
  "concept-visual": "concept", "single-answer-quiz": "quiz", "exit-ticket": "exit",
  process: "worked-example", timeline: "worked-example", steps: "worked-example",
  matching: "concept", "comparison-table": "comparison",
  hotspots: "concept", sorting: "concept", "motion-path": "simulation",
};
const recognized = new Set([
  "slide id", "layout", "title", "visible content", "body", "explanation", "teacher notes",
  "question", "options", "correct option", "answer", "feedback", "reveal", "visual",
  "animation", "interaction", "accessibility", "solution visibility", "left header",
  "right header", "comparison rows", "transition", "steps", "pairs", "activity prompt", "hotspots", "categories", "sorting", "first leg", "second leg", "duration",
]);
const cleanItem = (text: string) => text.replace(/^\s*[-*]\s+/, "").trim();

/** Deterministic mapping only: unsupported instructions remain in source and warnings. */
export function importScript(text: string): Slide[] {
  if (!text.trim()) throw Error("Add a script before creating drafts.");
  if (text.length > 100000) throw Error("Split this script into sessions of 100,000 characters or fewer.");
  const headings = [...text.matchAll(/^#{1,4}\s+(?:Slide|Screen)\s+(\d+)\s*[:.\-—–]?\s*(.*)$/gim)];
  if (headings.length > 80) throw Error("Split this script into sessions of 80 slides or fewer.");
  if (!headings.length) return [{ ...newSlide("Imported script"), body: "",
    notes: text.slice(0, 12000), warnings: ["No numbered slide headings found. Source retained; split and map the content manually."] }];
  return headings.map((heading, index) => {
    const section = text.slice(heading.index! + heading[0].length, headings[index + 1]?.index ?? text.length).trim();
    const slide = newSlide(heading[2].slice(0, 400) || `Slide ${heading[1]}`);
    const fields: Record<string, string> = {};
    let key = "", unstructured = "";
    for (const line of section.split(/\r?\n/)) {
      // A leading list marker belongs to the active field, not a new field.
      const match = line.match(/^\s*(?:\*\*)?([A-Za-z][A-Za-z /-]*?)(?:\*\*)?\s*:(?:\*\*)?\s*(.*)$/);
      if (match) {
        key = match[1].trim().toLowerCase();
        if (key in fields) slide.warnings.push(`Repeated field: ${key}. Check the combined content.`);
        fields[key] = [fields[key], match[2]].filter(Boolean).join("\n");
      } else if (key) fields[key] += `\n${line}`;
      else unstructured += `${line}\n`;
    }
    for (const name of Object.keys(fields)) if (!recognized.has(name))
      slide.warnings.push(`Unmapped field: ${name}. Original instructions remain in the session script.`);
    const field = (name: string, limit: number) => {
      const value = (fields[name] || "").trim();
      if (value.length > limit) slide.warnings.push(`${name} exceeds the editable field limit; full text remains in the script.`);
      return value.slice(0, limit);
    };
    slide.title = field("title", 400) || slide.title;
    slide.body = field("visible content", 12000) || field("body", 12000) || field("explanation", 12000);
    slide.notes = field("teacher notes", 12000);
    if (unstructured.trim()) {
      slide.notes = [slide.notes, unstructured.trim()].filter(Boolean).join("\n\n").slice(0, 12000);
      slide.warnings.push("Unstructured content retained in notes. Review before putting it on the slide.");
    }
    const layout = field("layout", 200).toLowerCase();
    if (templates.includes(layout as Template)) slide.template = layout as Template;
    else if (aliases[layout]) slide.template = aliases[layout];
    else if (layout) slide.warnings.push(`Layout "${layout}" is not supported yet; choose a layout in the editor.`);
    slide.visualBrief = field("visual", 12000);
    if (slide.visualBrief) slide.warnings.push("Visual requirements retained as a brief; assets and 2D/3D scenes are not generated by this parser.");
    for (const name of ["animation", "interaction", "accessibility", "solution visibility"])
      if (fields[name]?.trim()) slide.warnings.push(`${name}: requires manual review; these instructions are not automatically implemented.`);
    if (fields.transition) {
      const transition = fields.transition.trim().toLowerCase();
      if (["none", "fade", "rise"].includes(transition)) slide.transition = transition as Slide["transition"];
      else slide.warnings.push("Unsupported transition; default fade retained.");
    }
    const question = field("question", 2000);
    const requestedActivities = [!!(slide.template === "quiz" || question), !!fields.reveal, !!fields["comparison rows"], !!fields.steps, !!fields.pairs].filter(Boolean).length;
    if (requestedActivities > 1)
      slide.warnings.push("Multiple activity instructions found. Review the selected activity and split remaining instructions into separate slides.");
    if (slide.template === "quiz" || question) {
      const options = (fields.options || "").split(/\r?\n/).map(cleanItem).filter(Boolean);
      const optionLabels = options.map((option) => option.match(/^([A-H])[):.]\s*/i)?.[1]?.toUpperCase());
      const values = options.map((option) => option.replace(/^[A-H][):.]\s*/i, ""));
      const correct = field("correct option", 1000) || field("answer", 1000);
      const answerIndex = optionLabels.indexOf(correct.toUpperCase());
      const answer = answerIndex >= 0 ? values[answerIndex] : correct;
      slide.template = "quiz";
      if (values.length >= 2 && values.length <= 8 && values.every((v) => v.length <= 1000) &&
          new Set(values).size === values.length && values.includes(answer)) {
        slide.interaction = { type: "quiz", prompt: question || slide.title, options: values,
          answer, feedback: field("feedback", 2000), speed: 1 };
      } else slide.warnings.push("Quiz is inactive: provide 2–8 distinct options and a matching correct option. No answer was invented.");
    } else if (fields.reveal) {
      slide.interaction = { type: "reveal", prompt: question, options: [], answer: "",
        feedback: field("reveal", 2000), speed: 1 };
    } else if (slide.template === "comparison" && fields["comparison rows"]) {
      const rows = fields["comparison rows"].split(/\r?\n/).map(cleanItem).filter(Boolean).map((row) => row.split("|").map((cell) => cell.trim()));
      if (rows.length >= 1 && rows.length <= 8 && rows.every((row) => row.length === 3 && row[0].length <= 300 && row.every((cell) => cell.length > 0 && cell.length <= 1000))) {
        slide.activity = newActivity("table");
        slide.activity.headers = [field("left header", 200) || "Left", field("right header", 200) || "Right"];
        slide.activity.items = rows.map((row) => ({id: crypto.randomUUID(), label: row[0], value: row[1], extra: row[2]}));
      }
      else slide.warnings.push("Comparison requires Label | Left | Right rows within the content limit; map these manually.");
    }
    if (fields.steps || fields.pairs) {
      if (slide.interaction.type !== "none" || slide.activity || (fields.steps && fields.pairs))
        slide.warnings.push("Multiple activities requested on one slide. Split them into separate slides; extra steps/pairs were not applied.");
      else {
        const kind = fields.pairs ? "matching" : "steps";
        const rows = (fields.pairs || fields.steps).split(/\r?\n/).map(cleanItem).filter(Boolean).map((row) => row.split("|").map((cell) => cell.trim()));
        const distinct = kind !== "matching" || [0, 1].every((i) => new Set(rows.map((row) => row[i]?.toLowerCase())).size === rows.length);
        if (rows.length >= (kind === "matching" ? 2 : 1) && rows.length <= 8 && distinct && rows.every((row) => row.length === 2 && row[0].length <= 300 && row.every((cell) => cell.length > 0 && cell.length <= 1000))) {
          slide.activity = newActivity(kind);
          slide.activity.items = rows.map((row) => ({id: crypto.randomUUID(), label: row[0], value: row[1], extra: ""}));
        } else slide.warnings.push(`${kind}: use ${kind === "matching" ? "2" : "1"}–8 Label | Content rows within the field limits; matching labels and answers must be distinct.`);
      }
    }
    if (slide.activity) slide.activity.prompt = field("activity prompt", 2000);
    if (fields.hotspots || fields.sorting || layout === "motion-path") {
      if (slide.activity || slide.interaction.type !== "none" || [!!fields.hotspots,!!fields.sorting,layout === "motion-path"].filter(Boolean).length > 1) slide.warnings.push("Conflicting activities: split these instructions into separate slides.");
      else if (layout === "motion-path") {
        const firstLeg=Number(fields["first leg"]),secondLeg=Number(fields["second leg"]),duration=fields.duration ? Number(fields.duration) : 8;
        if(firstLeg>=1&&firstLeg<=100&&secondLeg>=1&&secondLeg<=100&&duration>=2&&duration<=60)
          slide.scene={version:1,kind:"motion-path",firstLeg,secondLeg,duration,yaw:35,elevation:35,cinematic:true,color:"#55d9f5"};
        else slide.warnings.push("Motion scene requires First leg and Second leg in metres (1–100); Duration is 2–60 seconds.");
      } else {
        const kind=fields.hotspots ? "hotspots" : "sorting", rows=(fields.hotspots||fields.sorting).split(/\r?\n/).map(cleanItem).filter(Boolean).map((r)=>r.split("|").map((c)=>c.trim()));
        const categories=(fields.categories||"").split("|").map((c)=>c.trim());
        const valid=rows.length>=1&&rows.length<=8&&rows.every((r)=>r[0]?.length>0&&r[0].length<=300&&r[1]?.length>0&&r[1].length<=1000&&(kind==="hotspots" ? r.length===4&&Number(r[2])>=5&&Number(r[2])<=95&&Number(r[3])>=5&&Number(r[3])<=95 : r.length===2&&categories.includes(r[1])))&&(kind!=="sorting"||(categories.length===2&&categories.every((c)=>c.length>0&&c.length<=200)&&new Set(categories.map((c)=>c.toLowerCase())).size===2));
        if(valid){slide.activity=newActivity(kind);slide.activity.prompt=field("activity prompt",2000);slide.activity.headers=kind==="sorting"?categories:[];slide.activity.items=rows.map((r)=>({id:crypto.randomUUID(),label:r[0],value:r[1],extra:"",...(kind==="hotspots"?{x:Number(r[2]),y:Number(r[3])}:{})}));if(kind==="hotspots")slide.warnings.push("Select an uploaded hotspot image in the activity editor, or use the empty board.");}
        else slide.warnings.push("Invalid hotspot/sorting rows. Use Label | Explanation | X | Y (5–95), or Item | Category with two Categories separated by |.");
      }
    }
    if (!slide.body && slide.interaction.type === "none" && !slide.activity && !slide.scene) slide.warnings.push("No visible content mapped. Add student-facing content before presenting.");
    slide.warnings = slide.warnings.slice(0, 30);
    return slide;
  });
}
